export function pageLangResolve(lang) {
  const k = String(lang || '').toLowerCase();
  if (!k) return 'uz';
  if (k.startsWith('ru')) return 'ru';
  if (k.startsWith('en')) return 'en';
  if (k.includes('cyrl') || k === 'uz-cyrl') return 'uz-cyrl';
  return 'uz';
}

