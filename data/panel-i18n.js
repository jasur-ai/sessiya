export const PANEL_LANGS = ['uz', 'uz-cyrl', 'ru', 'en'];

export function resolvePanelLang(lang) {
  const k = String(lang || '').toLowerCase();
  if (!k) return 'uz';
  if (k.startsWith('ru')) return 'ru';
  if (k.startsWith('en')) return 'en';
  if (k.includes('cyrl') || k === 'uz-cyrl') return 'uz-cyrl';
  return 'uz'; // 'kk', 'uz' va boshqa — uz fallback
}

export function htmlLangOf(code) {
  return { uz: 'uz', 'uz-cyrl': 'uz-Cyrl', ru: 'ru', en: 'en' }[code] || 'uz';
}

export function localeOf(code) {
  return { uz: 'uz-UZ', 'uz-cyrl': 'uz-Cyrl-UZ', ru: 'ru-RU', en: 'en-US' }[code] || 'uz-UZ';
}

