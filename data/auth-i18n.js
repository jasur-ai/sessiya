export const DEFAULT_AUTH_LANG = 'uz';

export function resolveAuthLang(lang) {
  const k = String(lang || 'uz').toLowerCase();
  if (k.startsWith('ru')) return 'ru';
  if (k.startsWith('en')) return 'en';
  if (k.includes('cyrl') || k === 'uz-cyrl') return 'uz-cyrl';
  return 'uz';
}

